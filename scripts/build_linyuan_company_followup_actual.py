"""Derive a complete automatic, cached-source company-followup trial."""
from pathlib import Path
import yaml
from build_linyuan_automatic_preview import build

ROOT=Path(__file__).resolve().parents[1]


def build_trial():
    result=build()
    result['name']='真实母片省略称呼追问验收（不入库不投稿）'
    result['run-name']='完整访谈漏选复测 · ${{ github.run_id }}'
    result['on']={'push':{'branches':['fix/company-followup-question-boundaries-20261023'],
        'paths':['.github/linyuan-company-followup-actual.trigger']}}
    result['concurrency']={'group':'company-followup-actual-${{ github.ref }}','cancel-in-progress':False}
    result['env'].update(RUN_SOURCE='https://www.bilibili.com/video/BV1se411H7tj',
        RUN_SLUG='preview-${{ github.run_id }}',RUN_RECOVERY_RUN_ID='39985269866',
        RUN_SOURCE_PLATFORM='bilibili',RUN_TEXT_MODEL='qwen3.5:9b',
        LINYUAN_EDITORIAL_PROFILE='field-story-v1',OUTPUT_LAYOUT='portrait')
    production=yaml.safe_load((ROOT/'.github/workflows/linyuan-produce-cn.yml').read_text())
    guard=next(s for s in production['jobs']['produce']['steps'] if s.get('id')=='source_admission')
    omitted={'读取全自动预览请求（不接受标题或选段答案）','恢复同源未完成下载',
        '下载缓存被淘汰时恢复独立母片检查点','保存未完成下载供下一次续传',
        '保存完整母片供后续取景失败及选段重试复用','独立保存已通过素材检查的完整母片'}
    steps=[]
    for s in result['jobs']['preview']['steps']:
        if s.get('name') in omitted:continue
        if s.get('id')=='source_cache_key':steps.append(guard)
        if s.get('id')=='src':
            s['name']='恢复同一完整母片检查点（不重新下载上游视频）'
            s['env']={'GH_TOKEN':'${{ github.token }}'}
            s['run']='''set -euo pipefail
mkdir -p _src
curl -fLsS --retry 2 --max-time 300 -H "Authorization: Bearer $GH_TOKEN" \\
  "https://api.github.com/repos/$GITHUB_REPOSITORY/actions/artifacts/12422073680/zip" -o /tmp/company-followup-mother.zip
unzip -j -o /tmp/company-followup-mother.zip -d _src
rm /tmp/company-followup-mother.zip
python - <<'CHECK'
import hashlib
from pathlib import Path
assert hashlib.sha256(Path('_src/video.mp4').read_bytes()).hexdigest()=='6f5ddecc6db4f2045e37a83f63a7d3a122f08287ee1258e9c6f085abdb2b9c2d'
CHECK
echo 'path=_src/video.mp4' >> "$GITHUB_OUTPUT"
'''
        if s.get('name')=='复用同源失败任务的已完成证据':
            s['run']=s['run'].rstrip()+' --artifact-name preview-editorial-preview-39985269866\n'
        if s.get('id')=='render':s['env'].pop('SOURCE_VISUAL_CHAPTERS',None)
        steps.append(s)
        if s.get('name')=='验收真实实验交付（缺实验成片即失败）':
            steps.append(dict(name='独立复验本次实验原始成片、字幕及封面',run='''python - <<'VERIFY'
import hashlib,json,os
from pathlib import Path
from artifact_range import delivery_files
from publishing_experiment import actual_profile,TREATMENT
from source_supply import validate_part
root=Path('deliver')/os.environ['RUN_SLUG']
raw=(root/'meta.json').read_bytes();data=json.loads(raw)
rows=data if isinstance(data,list) else [data]
accepted=[]
for row in rows:
    if actual_profile(row)!=TREATMENT:continue
    files=delivery_files(row)
    assert all((root/name).is_file() for name in files)
    before={name:hashlib.sha256((root/name).read_bytes()).hexdigest() for name in files}
    issue=validate_part(row,root)
    assert issue is None,issue
    assert all(hashlib.sha256((root/name).read_bytes()).hexdigest()==sha for name,sha in before.items())
    accepted.append(dict(title=row['title'],resolution=row['resolution'],files=before))
assert accepted and (root/'meta.json').read_bytes()==raw
(root/'original_media_validation.json').write_text(json.dumps(dict(passed=True,
    accepted=accepted,metadata_unchanged=True,files_unchanged=True,
    diagnostic_only=True,registered_stock=False,published=False),ensure_ascii=False,indent=2))
VERIFY
'''))
            steps.append(dict(name='留存独立原始成片复验结果',uses='actions/upload-artifact@v4',
                **{'if':'always()','with':dict(name='company-followup-original-media-validation',
                path='linyuan/deliver/${{ env.RUN_SLUG }}/original_media_validation.json',
                **{'if-no-files-found':'warn'})}))
    result['jobs']['preview']['timeout-minutes']=120
    result['jobs']['preview']['steps']=steps
    return result


if __name__=='__main__':
    (ROOT/'.github/workflows/linyuan-company-followup-actual.yml').write_text(
        '# Generated by scripts/build_linyuan_company_followup_actual.py from production workflow.\n'
        +yaml.safe_dump(build_trial(),allow_unicode=True,sort_keys=False,width=110))
