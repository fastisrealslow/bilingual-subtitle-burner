"""Derive a cache-only, publication-free real-source fallback trial."""
from pathlib import Path
import yaml
from build_linyuan_automatic_preview import build

ROOT=Path(__file__).resolve().parents[1]


def build_trial():
    result=build()
    result['name']='真实失败母片普通备用验收（缓存源，不入库不投稿）'
    result['run-name']='真实母片回退验证 · ${{ github.run_id }}'
    result['on']={'push':{'branches':['fix/story-failure-baseline-backups-20261023'],
        'paths':['.github/linyuan-story-backup-actual.trigger']}}
    result['concurrency']={'group':'story-backup-actual-${{ github.ref }}','cancel-in-progress':False}
    result['env'].update(RUN_SOURCE='https://www.bilibili.com/video/BV1hS421X7Xd',
        RUN_SLUG='preview-${{ github.run_id }}',RUN_RECOVERY_RUN_ID='39944885125',
        RUN_SOURCE_PLATFORM='bilibili',RUN_TEXT_MODEL='qwen3.5:9b',
        LINYUAN_EDITORIAL_PROFILE='field-story-v1',OUTPUT_LAYOUT='portrait')
    production=yaml.safe_load((ROOT/'.github/workflows/linyuan-produce-cn.yml').read_text())
    guard=next(s for s in production['jobs']['produce']['steps'] if s.get('id')=='source_admission')
    omitted={'读取全自动预览请求（不接受标题或选段答案）','恢复同源未完成下载',
        '下载缓存被淘汰时恢复独立母片检查点','保存未完成下载供下一次续传',
        '保存完整母片供后续取景失败及选段重试复用','独立保存已通过素材检查的完整母片',
        '验收真实实验交付（缺实验成片即失败）'}
    steps=[]
    for s in result['jobs']['preview']['steps']:
        if s.get('name') in omitted:continue
        if s.get('id')=='source_cache_key':
            steps.append(guard)
        if s.get('id')=='src':
            s['name']='从实际任务检查点恢复完整母片（不重下上游视频）'
            s['env']={'GH_TOKEN':'${{ github.token }}'}
            s['run']='''set -euo pipefail
mkdir -p _src
curl -fLsS --retry 2 --max-time 180 -H "Authorization: Bearer $GH_TOKEN" \\
  "https://api.github.com/repos/$GITHUB_REPOSITORY/actions/artifacts/12497946616/zip" -o /tmp/story-backup-mother.zip
unzip -j -o /tmp/story-backup-mother.zip -d _src
rm /tmp/story-backup-mother.zip
python - <<'CHECK'
import hashlib
from pathlib import Path
assert hashlib.sha256(Path('_src/video.mp4').read_bytes()).hexdigest()=='fc8b5dc5ebf11a64b701bc871c60bc8af8eaf57599968aa6c5478d9c93cfb7f2'
CHECK
echo 'path=_src/video.mp4' >> "$GITHUB_OUTPUT"
'''
        if s.get('id')=='render':
            s['env'].pop('SOURCE_VISUAL_CHAPTERS',None)
        steps.append(s)
        if s.get('id')=='render':
            steps.append(dict(name='核对普通回退与真实文件哈希，不能算成实验成功',run='''python - <<'CHECK'
import hashlib,json,os
from pathlib import Path
from publishing_experiment import actual_profile,BASELINE
root=Path('deliver')/os.environ['RUN_SLUG']
result=json.loads((root/'experiment_production.json').read_text())
assert result['requested']=='field-story-v1' and result['fallback']
assert result['experiment_accepted']==0 and result['baseline_accepted']==1
meta=json.loads((root/'meta.json').read_text()); rows=meta if isinstance(meta,list) else [meta]
assert len(rows)==1 and actual_profile(rows[0])==BASELINE
row=rows[0]; final=root/row['final']
assert final.name==row['final'] and final.is_file()
assert hashlib.sha256(final.read_bytes()).hexdigest()==row['fingerprints']['sha256']
(root/'baseline_backup_actual.json').write_text(json.dumps(dict(passed=True,source_run_id=39944885125,
    old_accepted=0,new_accepted=1,actual_profile=BASELINE,final_sha256=row['fingerprints']['sha256'],
    resolution=row['resolution'],diagnostic_only=True,registered_stock=False,published=False),ensure_ascii=False,indent=2))
CHECK
'''))
    steps.append(dict(name='保存真实回退验收与批次报告',uses='actions/upload-artifact@v4',
        **{'if':'always()','with':{'name':'story-baseline-backup-verification-${{ github.run_id }}',
        'path':'linyuan/deliver/${{ env.RUN_SLUG }}/baseline_backup_actual.json\nlinyuan/deliver/${{ env.RUN_SLUG }}/experiment_production.json\nlinyuan/deliver/${{ env.RUN_SLUG }}/batch_report.json',
        'if-no-files-found':'warn'}}))
    result['jobs']['preview']['timeout-minutes']=120
    result['jobs']['preview']['steps']=steps
    return result


if __name__=='__main__':
    (ROOT/'.github/workflows/linyuan-story-backup-actual.yml').write_text(
        '# Generated by scripts/build_linyuan_story_backup_actual.py from the real production workflow.\n'
        +yaml.safe_dump(build_trial(),allow_unicode=True,sort_keys=False,width=110))
