"""Derive a publication-free preview from the real production workflow."""
import copy
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / '.github/workflows/linyuan-automatic-preview.yml'
REMOVED = {
    '上传成片到 Release', '准备 B站登录态', 'B 站投稿',
    '明确触发库存核验与自动补位', '复用同源失败任务的已完成证据',
    # A restricted source can be inspected in a publication-free diagnostic,
    # but this never opens its production or promotion admission.
    '核对新源及旧任务重试的已知准入限制',
}


def build(topic=False,crop=False,context=False):
    if sum((topic,crop,context))>1:raise ValueError('Choose one isolated preview experiment')
    custom=topic or crop or context
    variant='context' if context else 'crop' if crop else 'topic' if topic else ''
    production = yaml.safe_load((ROOT / '.github/workflows/linyuan-produce-cn.yml').read_text())
    job = copy.deepcopy(production['jobs']['produce'])
    steps = []
    for step in job['steps']:
        if step.get('name') in REMOVED:
            continue
        if context and step.get('name')=='CPU离线ASR与完整观点规则回归（失败不进入实产）':
            # Baseline fixtures intentionally contain no-context evidence.
            # Test default production plus explicit context/cache regression;
            # the actual inference steps still inherit finance-v1 globally.
            step['env']={**step.get('env',{}),'QWEN_ASR_CONTEXT_PROFILE':'none'}
            step['run']+='\npython -m pytest -q tests/test_linyuan_asr_context.py tests/test_linyuan_mother_cache_identity.py\n'
        if step.get('id') == 'render':
            step['env']['SOURCE_VISUAL_CHAPTERS']='false' if custom else 'true'
            if topic:step['env']['SOURCE_TOPIC_DISCOVERY']='true'
            step['run'] = step['run'].replace('--split-highlights \\', '--max-outputs "$RUN_MAX_OUTPUTS" \\\n            --split-highlights \\')
        if 'run' in step:
            for name in ('RUN_SOURCE', 'RUN_SLUG', 'RUN_SPEAKER', 'RUN_OCCASION', 'RUN_SOURCE_PLATFORM'):
                step['run'] = step['run'].replace('${{ env.' + name + ' }}', '$' + name)
        if step.get('uses', '').startswith('actions/upload-artifact@'):
            step['with']['name'] = 'preview-' + step['with']['name']
        steps.append(step)
        if step.get('uses', '').startswith('actions/checkout@'):
            request=f'.github/linyuan-{variant}-preview-request.json' if custom else '.github/linyuan-preview-request.json'
            steps.append(dict(name='读取全自动预览请求（不接受标题或选段答案）',
                **{'working-directory': '.', 'run': 'python3 scripts/linyuan_preview_request.py '+request}))
    job['steps'] = steps
    env = copy.deepcopy(production['env'])
    # Use the existing strict delivery identity, not a compact-validator bypass.
    # Legacy live previews retain their identity until their current jobs finish.
    slug='ly-preview-${{ github.run_id }}' if crop or context else 'preview-${{ github.run_id }}'
    env.update(RUN_SOURCE='', RUN_SLUG=slug, RUN_SPEAKER='林园',
        RUN_OCCASION='访谈', RUN_SOURCE_PLATFORM='', RUN_REVIEWED_PARTS='',
        LINYUAN_AUTOMATIC_ONLY='true', RUN_MAX_OUTPUTS='1')
    if context:env['QWEN_ASR_CONTEXT_PROFILE']='finance-v1'
    name='林园原声词表预览（不发布）' if context else '林园取景修复预览（不发布）' if crop else '林园原声话题预览（不发布）' if topic else '林园全自动预览（不发布）'
    return dict(name=name, **{
        'run-name': '全自动预览 · ${{ github.run_id }}',
        'on': {'push': {'branches': ['codex/yield45-topic-discovery-20261013'] if custom else ['codex/automatic-preview', 'codex/caption-sync-feed-cover', 'codex/yield45-recovery-20261013'],
                       'paths': [f'.github/linyuan-{variant}-preview-request.json', f'.github/workflows/linyuan-{variant}-preview.yml'] if custom else ['.github/linyuan-preview-request.json', '.github/workflows/linyuan-automatic-preview.yml']},
               'workflow_dispatch': {}},
        'permissions': {'contents': 'read', 'actions': 'read'},
        'concurrency': {'group': f'linyuan-{variant}-preview' if custom else 'linyuan-automatic-preview', 'cancel-in-progress': False if crop or context else True},
        'env': env, 'jobs': {'preview': job}})


if __name__ == '__main__':
    import sys
    topic='--topic' in sys.argv
    crop='--crop' in sys.argv
    context='--context' in sys.argv
    if topic:TARGET=ROOT/'.github/workflows/linyuan-topic-preview.yml'
    if crop:TARGET=ROOT/'.github/workflows/linyuan-crop-preview.yml'
    if context:TARGET=ROOT/'.github/workflows/linyuan-context-preview.yml'
    TARGET.write_text('# Generated by scripts/build_linyuan_automatic_preview.py; production steps are shared.\n'
                      + yaml.safe_dump(build(topic=topic,crop=crop,context=context), allow_unicode=True, sort_keys=False, width=110))
